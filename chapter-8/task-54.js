// remove item in array

const fruit = ["Melon", "Apel", "Pisang", "Semangka", "Buah Naga"];

// using pop() method to remove a item at end of array
fruit.pop();
console.log(fruit); // ['Melon', 'Apel', 'Pisang', 'Semangka']

// use shift() method to remove item at begining of array
fruit.shift();
console.log(fruit); // ['Apel', 'Pisang', 'Semangka']
