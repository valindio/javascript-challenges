// add item to array

const fruit = ["Apel", "Pisang", "Semangka"];

// using push() method to add a item at end of array
fruit.push("Buah Naga");
console.log(fruit); // ['Apel', 'Pisang', 'Semangka', 'Buah Naga']

// use unshift() method to add item at begining of array
fruit.unshift("Melon");
console.log(fruit); // ['Melon', 'Apel', 'Pisang', 'Semangka', 'Buah Naga']
